'use strict';
// Chromium prints editable SVG paths and shapes; unsupported SVG effects retain the
// exporter's per-object raster fallback. No screenshot or full-page bitmap is used.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawn } = require('node:child_process');
const { pathToFileURL } = require('node:url');
const { exportSvg } = require('./svg-exporter');
let active = false;
function browserPath() {
  return [process.env.ARTFORGE_CHROMIUM_PATH,
    'C:/Program Files/Google/Chrome/Application/chrome.exe',
    'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe']
    .find((p) => p && fs.existsSync(p));
}

// Chromium does not return object-level PDF editability metadata. These are
// renderer-dependent filter scopes, separate from explicit SVG raster fallbacks.
function filterRasterizationCandidates(doc) {
  const scopes=[];
  for(const layer of doc.layers || []) {
    if(layer.visible===false)continue;
    const objects=(layer.objects || []).filter(object=>object.visible!==false);
    if(layer.filter && Object.keys(layer.filter).length)scopes.push({scope:'layer',id:layer.id,objectIds:objects.map(object=>object.id),filters:Object.keys(layer.filter),status:'renderer-dependent',reason:'chromium-svg-filter-compositing'});
    for(const object of objects){const filters=[];if(Number(object.blur)>0)filters.push('blur');if(object.shadow)filters.push('shadow');if(filters.length)scopes.push({scope:'object',id:object.id,layerId:layer.id,type:object.type,filters,status:'renderer-dependent',reason:'chromium-svg-filter-compositing'});}
  }
  return scopes;
}

async function exportPdf(doc, options = {}) {
  if(typeof WebSocket!=='function') throw Object.assign(new Error('PDF requires Node with built-in WebSocket support'),{code:'PDF_RUNTIME_UNSUPPORTED'});
  const executable = browserPath();
  if (!executable) throw Object.assign(new Error('Install Chromium or configure ARTFORGE_CHROMIUM_PATH'), { code: 'PDF_BROWSER_UNAVAILABLE' });
  if (active) throw Object.assign(new Error('A PDF export is already running; retry after it completes'), { code: 'PDF_BUSY' });
  require('./operation-context').checkpoint();
  active = true;
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'artforge-pdf-'));
  let child, ws;
  const operation=require('./operation-context').context.getStore();
  const cancel=()=>{const error=Object.assign(new Error('PDF export cancelled before commit'),{code:'OPERATION_CANCELLED'});for(const call of pending.values()){clearTimeout(call.timer);call.reject(error);}pending.clear();if(child&&child.exitCode===null)child.kill();};
  let exportWarnings=[];
  const pending = new Map();
  let seq = 0;
  const deadline = Date.now() + 30000;
  const check = () => require('./operation-context').checkpoint();
  const pause = async () => {check(); await new Promise(resolve=>setTimeout(resolve,50)); check();};
  const send = (method, params = {}) => new Promise((resolve, reject) => {
    check();
    const id = ++seq;
    const timer = setTimeout(() => { pending.delete(id); reject(new Error('PDF protocol timeout')); }, Math.max(1,Math.min(15000,deadline-Date.now())));
    pending.set(id, { resolve, reject, timer });
    ws.send(JSON.stringify({ id, method, params }));
  });
  try {
    operation?.signal.addEventListener('abort',cancel,{once:true});
    const result = exportSvg(doc, options);
    const rasterizationCandidates=filterRasterizationCandidates(doc);
    const svgSourceStats={vectorObjects:result.vectorObjects,textObjects:result.textObjects,explicitRasterFallbacks:result.rasterized.length};
    const pdfObservedStats={status:'not-collected-at-runtime',reason:'Chromium print does not expose per-object PDF operator metadata'};
    if(rasterizationCandidates.length)result.warnings.push('PDF filter compositing may rasterize affected objects/layers. Legacy counts describe SVG source objects, not observed PDF editability; inspect rasterizationCandidates.');
    exportWarnings=result.warnings;
    // SVG is generated by our exporter, never arbitrary HTML submitted by a caller.
    const html = `<html><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; font-src data:; img-src data:; style-src 'unsafe-inline'; script-src 'none'"><style>@page{size:${doc.canvas.width}px ${doc.canvas.height}px;margin:0}html,body{margin:0;padding:0}svg{display:block}*{print-color-adjust:exact}</style></head><body>${result.svg.replace(/<\?xml[^>]*\?>/, '')}</body></html>`;
    fs.writeFileSync(path.join(dir, 'scene.html'), html);
    child = spawn(executable, ['--headless', '--disable-gpu', '--no-first-run', '--no-default-browser-check', '--disable-background-networking', '--remote-debugging-port=0', `--user-data-dir=${dir}/profile`, 'about:blank'], { windowsHide: true, stdio: 'ignore' });
    let launchError;
    child.on('error', (error) => { launchError = error; });
    let port;
    while (!port) {
      if (launchError) throw launchError;
      if (Date.now() > deadline || child.exitCode !== null) throw new Error('PDF browser failed to start');
      // Windows may expose the file while Chrome still owns its creation lock,
      // or before the port line is complete. Probe readiness, not the print job.
      try {
        const candidate=Number(fs.readFileSync(path.join(dir,'profile/DevToolsActivePort'),'utf8').split('\n')[0]);
        if(Number.isInteger(candidate)&&candidate>0&&candidate<=65535)port=candidate;
      } catch(error) {if(!['ENOENT','EBUSY','EACCES','EPERM'].includes(error.code))throw error;}
      if(port)break;
      await pause();
    }
    // DevToolsActivePort can precede HTTP readiness, especially under render load.
    // Probe the existing blank target with idempotent GETs; never retry printing.
    let target;
    while(Date.now()<deadline) {
      try { const targets=await fetch(`http://127.0.0.1:${port}/json/list`,{signal:AbortSignal.timeout(1000)}).then(r=>r.json());target=targets.find(t=>t.type==='page'&&t.webSocketDebuggerUrl);if(target)break; }
      catch(error) { if(child.exitCode!==null)throw new Error('PDF browser exited during readiness'); }
      await pause();
    }
    if(!target)throw Object.assign(new Error('PDF browser readiness deadline exceeded'),{code:'PDF_TIMEOUT'});
    ws = new WebSocket(target.webSocketDebuggerUrl);
    await new Promise((resolve, reject) => { const timer=setTimeout(()=>reject(new Error('PDF websocket timeout')),5000); ws.addEventListener('open', ()=>{clearTimeout(timer);resolve();}, {once:true}); ws.addEventListener('error', ()=>{clearTimeout(timer);reject(new Error('PDF websocket failure'));}, {once:true}); });
    ws.addEventListener('message', (event) => {
      const message = JSON.parse(event.data); const call = pending.get(message.id);
      if (!call) return;
      clearTimeout(call.timer); pending.delete(message.id);
      if (message.error) call.reject(new Error(message.error.message)); else call.resolve(message.result);
    });
    await send('Network.enable');
    await send('Network.setBlockedURLs', { urls: ['http://*', 'https://*'] });
    await send('Page.enable');
    await send('Page.navigate', { url: pathToFileURL(path.join(dir, 'scene.html')).href });
    while (true) {
      const ready = await send('Runtime.evaluate', { expression: 'document.readyState === "complete" && !!document.querySelector("svg")', returnByValue: true });
      if (ready.result.value) break;
      if (Date.now() > deadline) throw new Error('PDF document load timeout');
      await pause();
    }
    await send('Runtime.evaluate', { expression: 'document.fonts.ready.then(()=>true)', awaitPromise: true, returnByValue: true });
    check();
    const pdf = await send('Page.printToPDF', { printBackground: true, preferCSSPageSize: true, displayHeaderFooter: false });
    check();
    const rawBuffer = Buffer.from(pdf.data, 'base64');
    const textRepair = require('./pdf-text').repairPdfText(rawBuffer);
    const buffer = textRepair.buffer;
    if(textRepair.atomicLigatures) result.warnings.push('PDF preserves atomic Arabic ligature mappings; some readers return presentation characters. Mixed-direction copy order varies by reader.');
    if (buffer.subarray(0, 5).toString() !== '%PDF-') throw new Error('Invalid PDF response');
    return { buffer, statsBasis:'svg-source-object-counts', svgSourceStats, pdfObservedStats, rasterizationCandidates, vectorObjects: result.vectorObjects, textObjects: result.textObjects, rasterized: result.rasterized, warnings: result.warnings, backend: 'chromium-svg-print', textRepair: { normalizedMaps: textRepair.normalizedMaps, flattenedStreams: textRepair.flattenedStreams, atomicLigatures: textRepair.atomicLigatures, mappingPolicy: 'single-codepoint canonical; atomic ligatures preserved' } };
  } catch(error) {
    if(operation?.signal.aborted)error=Object.assign(new Error('PDF export cancelled before commit'),{code:'OPERATION_CANCELLED'});
    else if(error.name==='TimeoutError' || error.name==='AbortError') error=Object.assign(new Error('PDF deadline exceeded'),{code:'PDF_TIMEOUT'});
    else if(typeof error.code!=='string') error.code="PDF_EXPORT_FAILED";
    throw error;
  } finally {
    operation?.signal.removeEventListener('abort',cancel);
    if (ws) {try {ws.close();} catch {exportWarnings.push('PDF browser connection cleanup was delayed');}}
    for (const call of pending.values()) { clearTimeout(call.timer); call.reject(new Error('PDF session closed')); }
    if (child && child.exitCode === null) {
      child.kill();
      await Promise.race([new Promise((resolve) => child.once('exit', resolve)), new Promise((resolve) => setTimeout(resolve, 2000))]);
    }
    // Chromium child processes can release profile files a moment after the parent.
    try { fs.rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 }); } catch {exportWarnings.push('Temporary PDF profile cleanup was delayed; OS temp cleanup may be needed');}
    active = false;
  }
}
module.exports = { exportPdf, browserPath };



